// 個人情報っぽい入力（電話番号・メール・住所など）には見守り番のフクロウが注意する
const PERSONAL_INFO = /\d{3,}|@|＠|丁目|番地|〒/;

export function opinionsFor(change, value, { colorName } = {}) {
  switch (change) {
    case 'color':
      if (!value) return [say(Y, 'はじめの色に戻した。ここの基本の色だ。')];
      if (colorName && COLOR_LINES[colorName]) return COLOR_LINES[colorName];
      return [say(Y, `カラーコード ${value}。こだわりを感じる。`), say(U, 'オリジナルの推しカラー！ すてき ♪')];
    case 'pattern':
      return PATTERN_LINES[value] || [];
    case 'mark':
      return MARK_LINES[value] || [say(U, 'かわいいマーク ♪')];
    case 'oshiName':
      if (!value) return [say(S, '推しの名前、消したっすね。また教えてほしいっす！')];
      if (PERSONAL_INFO.test(value)) {
        // フクロウが留守でも、だれかが必ず注意する
        return [
          say(F, 'ほう…数字やメール、住所のようなものは書かないほうが安全ですぞ。推しの名前だけにしておきなされ。'),
          say(Y, '電話番号や住所に見えるものは書かないほうがいい。推しの名前だけにしよう。'),
          say(S, 'それ、個人情報っぽいっす…！ 推しの名前だけにしておくっす！'),
          say(U, 'あっ、数字やメールは書かないほうが安心だよ〜。推しの名前だけにしよ ♪'),
        ];
      }
      return [
        say(S, `${value}さんが推しなんすね！ オレも応援するっす！`),
        say(U, `${value}、すてき〜！ 推しの歌、つくっちゃおうかな ♪`),
      ].sort(() => Math.random() - 0.5);
    case 'sparkle':
      return value
        ? [say(U, 'キラキラ〜！ ステージみたい ♪'), say(S, 'まぶしいっす！')]
        : [say(F, 'ほう、落ち着きましたな。')];
    case 'sticker':
      return value
        ? [say(S, 'シールいっぱいっす！ 推し活ノートみたいっす！')]
        : [say(Y, 'シールをはがした。すっきりだ。')];
    case 'typeface':
      return TYPEFACE_LINES[value] || [];
    case 'reset':
      return [say(Y, 'はじめの見た目に戻した。いつでも試せるのが、いい設計だ。'), say(S, 'また着がえたくなったら、いつでも呼んでほしいっす！')];
    default:
      return LAYOUT_LINES[change]?.[value] || [];
  }
}

// 閉じたときのまとめのひとこと（遊び場のキャラが言う）
export function closingLines(design) {
  const lines = [say(S, 'きせかえ、おつかれさまっす！ にあってるっす！')];
  if (design.color) lines.push(say(U, '推しカラーの画面、テンション上がるね ♪'));
  if (design.oshiName && !PERSONAL_INFO.test(design.oshiName)) lines.push(say(F, `ほう、${design.oshiName}さん推しの画面ですな。`));
  lines.push(say(Y, '見た目が変わっても、中身はちゃんと動いている。安心してくれ。'));
  return lines;
}

